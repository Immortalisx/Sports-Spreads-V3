import test from 'node:test';
import assert from 'node:assert/strict';
import {planPregamePropRefresh} from '../supabase/functions/daily-tickets/prop-refresh-plan.mjs';
const now=new Date('2026-11-18T20:00:00Z');
const event={id:'0123456789abcdef0123456789abcdef',commence_time:'2026-11-18T20:45:00Z'};
const rows=[{league:'nfl',fetched_at:'2026-11-18T19:50:00Z',snapshot:{events:[event]}}];
test('player props are opt-in and no requests are generated by default',()=>{
 const x=planPregamePropRefresh(rows,{now});
 assert.equal(x.status,'disabled');
 assert.equal(x.requests.length,0);
});
test('final hour NFL planner estimates all market credits before execution',()=>{
 const x=planPregamePropRefresh(rows,{now,enabled:true,monthlyRemaining:50,maxCreditsPerRun:4});
 assert.equal(x.status,'planned');
 assert.equal(x.estimatedCredits,4);
 assert.equal(x.requests[0].sportKey,'americanfootball_nfl');
 assert.equal(x.requests[0].regions[0],'us');
});
test('planner blocks over-budget batches atomically',()=>{
 const x=planPregamePropRefresh(rows,{now,enabled:true,monthlyRemaining:3,maxCreditsPerRun:4});
 assert.equal(x.status,'blocked');
 assert.equal(x.reason,'budget_exceeded');
 assert.deepEqual(x.requests,[]);
});
test('planner rejects stale games and bad identifiers',()=>{
 const stale=[{...rows[0],fetched_at:'2026-11-18T10:00:00Z'}];
 assert.equal(planPregamePropRefresh(stale,{now,enabled:true,monthlyRemaining:50,maxCreditsPerRun:10}).status,'empty');
 assert.equal(planPregamePropRefresh([{...rows[0],snapshot:{events:[{...event,id:'unsafe'}]}}],{now,enabled:true,monthlyRemaining:50,maxCreditsPerRun:10}).status,'empty');
});
