import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const build=read('scripts/build-app.mjs');
const names=[...build.matchAll(/'([0-9]{2}-[a-z-]+)'/g)].map(x=>x[1]);
const modules=names.map(n=>({name:n,src:read('src/app/'+n+'.js')}));
const combined=modules.map(m=>m.src).join('\n\n');
const bundle=read('public/app.js');
const html=read('index.html');
const expected='/* Generated by npm run build:app — edit src/app, not public/app.js. */\n'+combined;
test('source build includes all V4 feature modules exactly once in a stable order',()=>{
 assert.equal(names.length,13);
 assert.equal(new Set(names).size,names.length);
 for(const n of ['26-cached-research','27-board-team-loaders','28-odds-signals','29-cloud-ticket-services','29-ticket-autocomplete-generator','30-controller'])assert.ok(names.includes(n),n);
 assert.equal(names.at(-1),'30-controller');
});
test('published app bundle is byte-for-byte source assembly',()=>assert.equal(bundle,expected));
test('standalone root embeds the same source-built app bundle',()=>assert.ok(html.includes(bundle)));
test('all critical loaders exist once across modules',()=>{
 for(const name of ['loadBoard','loadTeams','loadTeam','loadNflAvailability','loadNhlGoalies','loadCurrentSeasonForm','loadPregameSignals','loadSportsbookOdds','generateAutomaticTicket','loadDailySuggestions']){
  const hits=[...combined.matchAll(new RegExp('(?:async\\s+)?function\\s+'+name+'\\s*\\(','g'))];
  assert.equal(hits.length,1,name+' should have one definition');
 }
});
