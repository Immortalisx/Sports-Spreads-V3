import {createServer} from 'node:http';
import {readFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {cloudConfig,cloudTickets,CloudError} from './lib/cloud.mjs';
import {getScoreboard,getTeams,getTeam,getRoster,getInjuries,getNews,UpstreamError,LEAGUES} from './lib/espn.mjs';

const ROOT=path.dirname(fileURLToPath(import.meta.url));
const PUBLIC=path.join(ROOT,'public');
const PORT=Number(process.env.PORT||4173);
const CONTENT={'.html':'text/html; charset=utf-8','.css':'text/css; charset=utf-8','.js':'text/javascript; charset=utf-8','.svg':'image/svg+xml','.json':'application/json; charset=utf-8'};
const EXTERNAL='No official prediction engine has been connected. Odds and models are not generated by this prototype.';
function json(res,status,data) {
  res.writeHead(status,{'content-type':'application/json; charset=utf-8','cache-control':'no-store','x-content-type-options':'nosniff'});
  res.end(JSON.stringify(data));
}
async function api(res,url) {
  const parts=url.pathname.split('/').filter(Boolean);
  const league=url.searchParams.get('league')||'nba';
  if(url.pathname==='/api/status') return json(res,200,{name:'Sports Spreads v3',version:'0.3.0',leagues:Object.keys(LEAGUES),modelConnected:false,predictionStatus:EXTERNAL});
  if(url.pathname==='/api/scoreboard')return json(res,200,await getScoreboard(league,url.searchParams.get('date')));
  if(url.pathname==='/api/teams')return json(res,200,await getTeams(league));
  if(parts[1]==='team'&&parts.length===4){
    const [,,sport,id]=parts;
    const view=url.searchParams.get('view')||'profile';
    let payload;
    if(view==='profile')payload=await getTeam(sport,id);
    else if(view==='roster')payload=await getRoster(sport,id);
    else if(view==='injuries')payload=await getInjuries(sport,id);
    else if(view==='news')payload=await getNews(sport,id,url.searchParams.get('name')||'');
    else return json(res,400,{error:'Unsupported view'});
    return json(res,200,payload);
  }
  return json(res,404,{error:'API route not found'});
}
async function handler(req,res){
  if(req.url?.split('?')[0]==='/api/cloud/config'&&req.method==='GET'){
    const cfg=cloudConfig();return json(res,200,{configured:cfg.configured,auth:'user session required',url:cfg.configured?cfg.url:null,publishableKey:cfg.configured?cfg.key:null,mode:cfg.configured?'Supabase user-scoped':'local-only'});
  }
  if(req.url?.split('?')[0]==='/api/cloud/tickets'){
    if(!['GET','POST'].includes(req.method))return json(res,405,{error:'Method not allowed'});
    let body;
    if(req.method==='POST'){
      const chunks=[];let size=0;
      try{for await(const chunk of req){size+=chunk.length;if(size>16_384)return json(res,413,{error:'Ticket too large'});chunks.push(chunk);}body=JSON.parse(Buffer.concat(chunks).toString('utf8'));}
      catch{return json(res,400,{error:'Invalid JSON'});}
    }
    try{return json(res,200,{tickets:await cloudTickets({method:req.method,auth:req.headers.authorization,body})});}
    catch(e){return json(res,e instanceof CloudError?e.status:500,{error:e instanceof CloudError?e.message:'Unexpected storage error'});}
  }
  if(req.method!=='GET')return json(res,405,{error:'Read-only sports feed'});
  let url;
  try{url=new URL(req.url,'http://localhost');}catch{return json(res,400,{error:'Invalid request'});}
  if(url.pathname.startsWith('/api/')){
    try{return await api(res,url);}catch(e){return json(res,e instanceof UpstreamError?e.status:500,{error:e instanceof UpstreamError?e.message:'Unexpected error'});}
  }
  let requested=url.pathname==='/'?'index.html':url.pathname.slice(1);
  if(requested.includes('..')||requested.includes('\\')||requested.startsWith('.'))return json(res,403,{error:'Forbidden'});
  if(!['index.html','app.js','style.css','favicon.svg'].includes(requested))return json(res,404,{error:'Not found'});
  try{
    const buf=await readFile(path.join(PUBLIC,requested));
    res.writeHead(200,{'content-type':CONTENT[path.extname(requested)]??'application/octet-stream','cache-control':'no-cache','x-content-type-options':'nosniff'});
    res.end(buf);
  }catch{json(res,404,{error:'File not found'});}
}
export const server=createServer(handler);
if(process.argv[1]&&fileURLToPath(import.meta.url)===path.resolve(process.argv[1])){
  server.listen(PORT,()=>console.log(`Sports Spreads v3 at http://localhost:${PORT}`));
}
