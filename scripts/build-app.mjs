// Assemble the browser controller from reviewable modules. Intentionally emits
// a classic script so existing local tests and the no-framework site still work.
import {readFile,writeFile} from 'node:fs/promises';
import {join,dirname,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const sources=['00-feed','10-state','20-views','30-controller'];
const contents=await Promise.all(sources.map(async n=>readFile(join(root,'src','app',n+'.js'),'utf8')));
const code='/* Generated by npm run build:app — edit src/app, not public/app.js. */\n'+contents.join('\n\n');
await writeFile(join(root,'public','app.js'),code);
console.log(`Assembled ${sources.length} modules (${code.length} chars)`);
